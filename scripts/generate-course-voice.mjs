import {mkdirSync,writeFileSync,readFileSync,existsSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {coursePlans} from '../src/classes/course-plans.js';
import {courseAudioCues,courseCountInCues} from '../src/classes/course-audio-cues.js';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),folder=resolve(root,'public/audio/course-voice');
mkdirSync(folder,{recursive:true});
const texts=[...new Set([...Object.keys(coursePlans).flatMap(kind=>courseAudioCues(kind).map(c=>c.text)),...courseCountInCues.map(c=>c.text),'預覽到這裡結束。','準備好了，我們開始。','休息一下，調整呼吸。'])];
const phrases=texts.map(text=>{const id=createHash('sha256').update(text).digest('hex').slice(0,16);return{id,text,file:`${id}.wav`};});
const manifest={version:1,voice:'Microsoft Hanhan Desktop',language:'zh-TW',sampleRate:16000,channels:1,bitsPerSample:16,source:'Offline Windows System.Speech; original game cues, no branded recordings',phrases};
const manifestPath=resolve(folder,'manifest.json');writeFileSync(manifestPath,JSON.stringify(manifest,null,2));
if(!process.argv.includes('--manifest-only')){
  const result=spawnSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',resolve(root,'scripts/generate-course-voice.ps1'),'-ManifestPath',manifestPath],{stdio:'inherit',windowsHide:true});
  if(result.status!==0)throw new Error(`Offline speech generation failed (${result.status})`);
  for(const phrase of phrases){
    const file=resolve(folder,phrase.file);if(!existsSync(file))throw new Error(`Missing ${file}`);
    const wav=readFileSync(file);let offset=12,dataBytes=0;
    while(offset+8<=wav.length){const size=wav.readUInt32LE(offset+4);if(wav.toString('ascii',offset,offset+4)==='data'){dataBytes=size;break;}offset+=8+size+(size%2);}
    phrase.duration=dataBytes/(16000*2);phrase.bytes=wav.length;
  }
  writeFileSync(manifestPath,JSON.stringify(manifest,null,2));
}
const lookup=Object.fromEntries(phrases.map(p=>[p.text,{file:p.file,duration:p.duration||0}]));
writeFileSync(resolve(root,'src/classes/course-voice-manifest.js'),`// Generated by scripts/generate-course-voice.mjs; original offline zh-TW cues.\nexport const courseVoiceManifest=${JSON.stringify(lookup,null,2)};\n`);
console.log(JSON.stringify({phrases:phrases.length,bytes:phrases.reduce((n,p)=>n+(p.bytes||0),0),manifest:manifestPath}));
